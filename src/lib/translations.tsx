interface TranslationProviderProps {
  children: ReactNode;
  locale: Locale;
}

export function TranslationProvider({ children, locale }: TranslationProviderProps) {
  const validLocale: Locale = (locale === 'en' || locale === 'id') ? locale : 'en';

  // Keep the document language in sync for SEO / accessibility.
  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = validLocale;
    }
  }, [validLocale]);

  const t = (key: string): string => {
    const localeMessages = messages[validLocale];
    return localeMessages[key as keyof typeof messages['en']] || key;
  };

  return (
    <TranslationContext.Provider value={{ locale: validLocale, t }}>
      {children}
    </TranslationContext.Provider>
  );
}

export function useTranslations() {
  const context = useContext(TranslationContext);
  if (context === undefined) {
    throw new Error('useTranslations must be used within a TranslationProvider');
  }
  return context.t;
}

export function useLocale() {
  const context = useContext(TranslationContext);
  if (context === undefined) {
    throw new Error('useLocale must be used within a TranslationProvider');
  }
  return context.locale;
}
